import { onCurve, point, simpleLeaf, stem } from './botanical-geometry.mjs'

// Representative habitat motifs, not portraits of every species in a biome.
// Coordinates are shared by stems, leaf bases and roots to keep joins attached.
const path = (d, attrs = '') => `<path d="${d}" ${attrs}/>`
const group = (name, content, attrs = '') => `<g class="${name}" ${attrs}>${content}</g>`
const curve = (base, bend, tip) => ({ base, bend, tip })

function study(name, contours, content) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 460 510" fill="none" stroke="currentColor" stroke-width="1.15" stroke-linecap="round" stroke-linejoin="round">
  <!-- Generated by generators/habitat-studies.mjs (${name}); edit the scene, then pnpm artwork:generate. -->
  ${group('contours', path(contours), 'opacity=".35" stroke-width=".7"')}
  ${group('botanical', content)}
</svg>
`
}

function foliage(branches) {
  const leaves = branches.map(b => simpleLeaf(b, b.length, b.width))
  return group('stems', path(branches.map(stem).join(' '))) +
    group('leaves', leaves.map(l => path(l.outline)).join(''), 'fill="currentColor" fill-opacity=".08"') +
    group('midribs', path(leaves.map(l => l.midrib).join(' '))) +
    group('veins', path(leaves.map(l => l.veins).join(' ')), 'stroke-width=".65" opacity=".6"')
}

