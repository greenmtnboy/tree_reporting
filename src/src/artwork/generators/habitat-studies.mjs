export function generateMangroveSvg() {
  const { trunk, branches, roots } = mangroveScene
  const attached = list => list.map(b => ({ ...b, base: onCurve(trunk, b.at) }))
  const rootPaths = attached(roots).map(r => {
    const [x, y] = r.tip
    return `${stem(r)} L${x + 3} ${y} Q${point([r.bend[0] + 7, r.bend[1]])} ${point(r.base)}`
  }).join(' ')
  return study('mangrove',
    'M83 448q28-5 57 0 M182 457q20-4 36 0 M250 468q23-5 45 0 M331 453q13-3 25 0 M391 466q21-4 41 0 M124 482q40 7 79 0 M341 492q45 6 83-2',
    group('stems', path(stem(trunk))) + foliage(attached(branches)) +
    group('roots', path(rootPaths)) +
    group('pencil', path('M282 358q-5-34-7-63 M262 229l-4-30 M231 396q-19 27-25 48 M342 410l16 33'), 'stroke-width=".65" opacity=".6"'))
}

// A seasonally leaf-shedding tree: open branching and a few broad leaves,
