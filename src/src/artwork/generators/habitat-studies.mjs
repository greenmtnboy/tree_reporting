export function generateDryForestSvg() {
  const { trunk, limbs } = dryForestScene
  const branches = limbs.map(b => ({ ...b, base: onCurve(trunk, b.at) }))
  const twigs = branches.flatMap((b, i) => [
    curve(b.tip, [b.tip[0] - 7, b.tip[1] - 21], [b.tip[0] - 3, b.tip[1] - 39]),
    curve(onCurve(b, .64), [b.tip[0] + (i % 2 ? 27 : -27), b.tip[1] + 5], [b.tip[0] + (i % 2 ? 41 : -43), b.tip[1] - 6]),
  ])
  const leaves = [
    { ...twigs[0], length: 49, width: 21 },
    { ...twigs[3], length: 52, width: 23 },
    { ...twigs[4], length: 44, width: 20 },
    { ...twigs[6], length: 43, width: 19 },
  ]
  return study('dry-forest',
    'M61 489q71-20 137-8 M221 493q43-10 86 0 M344 499q42-7 85-22 M96 462l23-6 18 5 M367 472l19-7 21 3',
    group('stems', path([trunk, ...branches, ...twigs].map(stem).join(' '))) + foliage(leaves) +
    group('bark', path('M320 482q-29-107-27-204 M306 431l-7-32 M297 370l-5-32'), 'opacity=".6" stroke-width=".65"') +
    group('litter', path('M177 478q-17-21-39-9q18 19 39 9 M196 494q20-20 37-6q-19 14-37 6'), 'stroke-width=".8"'))
}

function blades(base, height, spread, count) {
  return Array.from({ length: count }, (_, i) => {
    const t = i / (count - 1)
    const tip = [base[0] + (t - .5) * spread, base[1] - height * (.52 + .48 * Math.sin(Math.PI * t))]
    const bend = [base[0] + (t - .5) * spread * .24, base[1] - height * .62]
    return `M${point(base)} Q${point(bend)} ${point(tip)} Q${point([bend[0] + 3, bend[1] + height * .23])} ${point(base)}`
  }).join(' ')
}

export const wetlandScene = {
  stems: [curve([254, 478], [244, 324], [223, 191]), curve([290, 489], [302, 301], [316, 144]), curve([330, 481], [367, 359], [375, 254])],
}

export function generateWetlandSvg() {
  const stems = wetlandScene.stems
  const heads = stems.map(s => {
    const [x, y] = s.tip
    return `M${x} ${y} C${x - 9} ${y - 19} ${x - 10} ${y - 47} ${x - 3} ${y - 52} C${x + 5} ${y - 55} ${x + 8} ${y - 14} ${x} ${y} Z`
  }).join(' ')
  const leaves = stems.flatMap((s, i) => [-1, 1].map(side => {
    const base = onCurve(s, .22 + i * .08)
    const tip = [base[0] + side * 65, base[1] - 127]
    return `M${point(base)} Q${point([base[0] + side * 10, base[1] - 106])} ${point(tip)} Q${point([base[0] + side * 31, base[1] - 47])} ${point(base)}`
  })).join(' ')
  return study('wetland',
    'M45 466q42-8 85 0t69 0 M91 488q63-6 126 0 M345 491q45 7 87-1 M359 458q35-5 72 1 M113 438q28-5 52 0 M238 503q31 4 62 0',
    group('stems', path(stems.map(stem).join(' '))) +
    group('seed-heads', path(heads), 'fill="currentColor" fill-opacity=".08"') +
    group('leaves', path(leaves)) +
    group('sedge', path(blades([187, 477], 138, 110, 6)), 'stroke-width=".85"'))
}

