"""Utrecht's municipal trees: the Gemeente Utrecht "bomenkaart".

Source: the `bomenkaart_2026` FeatureServer on the city's ArcGIS Online
organisation (owner `UTRECHT_GEO`, item f88d256383404e3ea1a5781876f33b0b),
catalogued on open.utrecht.nl as "bomenkaart 2026"
(https://open.utrecht.nl/dataset/bomenkaart-2026/ea248c2e-7ae4-47b3-bd57-f34b2d876667)
under CC BY 4.0.  "In Utrecht staan ongeveer 160.000 gemeentelijke bomen ...
Deze kaart wordt ieder kwartaal bijgewerkt": the city's own trees, refreshed
quarterly.  Both of the service's layers are read:

* 0 `Park_en_Straatbomen`, park and street trees: 137,135 rows on 2026-11-17;
* 1 `bomen_in_bosplantsoen`, trees in woodland plantings: 25,518.

Together 162,653, the "about 160,000" of the description.  `Eigenaar` is
`Gemeentelijk` on every row of both.

**The service is renamed now and then** (`Bomenkaart` until 2023,
`Bomenkaart_update_2024`, `bomenkaart_2026`; the catalogue's umbrella "Bomen"
record says "De URL is in 2026 gewijzigd").  `SERVICE` pins the current one,
and the freshness probe raises when the catalogue's "WFS actuele bomenkaart"
link names a different service, so a rename is a loud failure rather than a
city frozen on a deleted layer.

**Ids are `Boomnummer`**, the tree number the city's map shows and its
report-a-tree address carries (`maileenboom+1846968@utrecht.nl`): non-null
and distinct over all 162,653 rows of both layers, and stable across the
rename -- 152,081 of the 156,965 numbers in `Bomenkaart_update_2024` are
still there, 94% with the same species.  OBJECTID restarts at 1 in each layer
and is regenerated by each republish.  Published as `utrecht-{Boomnummer}`.

**Species is `Wetenschap`**, the scientific name with a quoted cultivar
(`Tilia x europaea 'Koningslinde'`); `Nederlands`, the Dutch common name, is
not read.  `parse_name` splits the cultivar off itself (the shared parser
stops at the first closing quote, which cuts `'Westhof's Glorie'`, 4,135
ashes, at the apostrophe), drops the placeholder cultivar `'CV'` and the
Dutch use notes in parentheses (`Malus 'CV' (sierappel)`, the ornamental
apple; `(consumptieappel)`, the eating apple), and strips an all-caps trade
name (`Zelkova serrata GREEN VASE ('Flekova')`).  The unidentified records
(`Niet bepaald`, `Niet in lijst`, `Niet te beoordelen`: 1,746 rows, Legenda
`Niet`) publish as `Unknown`; the few free-text notes in the column are
mapped by hand in `NAME_FIXES`.  `N.v.t. (boom niet aanwezig)` ("not
applicable, tree not present") and a stump note are not trees and are
dropped.

**`plantjaar` is the planting year**, an integer, published as 1 January of
it.  The spikes at 1970 (12,306) and 1980 (11,129) sit beside 1975 and 1985
and are the estimated plantings of a surveyed stock, not one stamped default;
kept.  The handful of impossible values (`-1`, `2`, `4`, `20247`) are nulled
by `parse_plant_date_year` and the schema.

No diameter, height or crown spread is published.
"""

import re
import sys
from collections import Counter
from pathlib import Path

import pyarrow as pa

sys.path.insert(0, str(Path(__file__).parent.parent))
from shared.platforms.arcgis import FeatureLayer, esri_point, iter_features
from shared.ingest import (
    UNKNOWN_SPECIES,
    emit,
    enforce_tree_schema,
    parse_plant_date_year,
    stream_to_table,
    validate_coordinates,
)

BASE = "https://services-eu1.arcgis.com/SMnoOtmU2UWf0vRp/arcgis/rest/services"
# Pinned; utrecht_update_time.py raises when the catalogue moves on from it.
SERVICE = "bomenkaart_2026"
LAYERS = {
    "park and street trees": FeatureLayer(f"{BASE}/{SERVICE}/FeatureServer/0", timeout=180),
    "woodland-planting trees": FeatureLayer(f"{BASE}/{SERVICE}/FeatureServer/1", timeout=180),
}
FIELDS = "OBJECTID,Boomnummer,Wetenschap,plantjaar"
ID_PREFIX = "utrecht-"

# `Wetenschap` values that record no identification.  `Niet bepaald` "not
# determined", `Niet in lijst` "not in the list", `Niet te beoordelen` "cannot
# be assessed", `Niet te herkennen` "not recognisable".
UNIDENTIFIED = frozenset(
    {"niet", "niet bepaald", "niet in lijst", "niet te beoordelen", "niet bekend",
     "niet te herkennen", "onbekend"}
)
# Values that say there is no tree at the point.
NOT_A_TREE = (
    "n.v.t. (boom niet aanwezig)",  # "not applicable (tree not present)", 43 rows
    "boom niet aanwezig",
    "stobbe",  # a stump still to be ground out
    "geen nieuwe soort",  # "no new species because of the redesign": nothing replanted
)
# Free text and unquoted cultivars in the species column, one or a few rows each.
NAME_FIXES = {
    "Ruwe iep (Ulmus glabra)": "Ulmus glabra",
    "Boom verplaatst stond te dich op andere. Nawee projecht": UNKNOWN_SPECIES,
    "Ecologisch monument, herplant in de buurt: 1x Castanea sativa": UNKNOWN_SPECIES,
    "Acer Rubrum Summerset": "Acer rubrum 'Summerset'",
    "Prunus Cerasifera Nigra": "Prunus cerasifera 'Nigra'",
    "Prunus Serrulata Kanzan": "Prunus serrulata 'Kanzan'",
    "Acer palmatum osakazuki": "Acer palmatum 'Osakazuki'",
    "Acer palmatum osazuki": "Acer palmatum 'Osakazuki'",
    "Malus Hellendoorn": "Malus 'Hellendoorn'",
    "Photinia red robbin": "Photinia x fraseri 'Red Robin'",
    "Photinia frassenii red robin": "Photinia x fraseri 'Red Robin'",
    "Pyracantha solei dor": "Pyracantha 'Soleil d'Or'",
    "Pterostrax corrymbus siebold": "Pterostyrax corymbosus",
    "Prunus padus nana": "Prunus padus 'Nana'",
    "Salix x chrysocoma Sepulcralis": "Salix x sepulcralis 'Chrysocoma'",
    "Pkrunus avium 'Bigarreau Burlat'": "Prunus avium 'Bigarreau Burlat'",
}
REPLACED_BY = re.compile(r"^vervangen door ([a-z]+ [a-z]+)", re.IGNORECASE)

QUOTES = "'‘’‚‛`�"
# Placeholder cultivars: "some cultivar".
PLACEHOLDER_CULTIVARS = frozenset({"cv", "cv.", "sp", "sp."})
# A trailing lower-case Dutch note in parentheses: `(sierappel)`, `(hoogstam)`.
TRAILING_NOTE = re.compile(r"\s*\([a-z][^()]*\)\s*$")
# `cv.` or `cultivars` written where a cultivar name would go (`Malus cv.`).
CV_WORD = re.compile(r"\s+(?:cv\.?|cultivars?)(?=\s|$)", re.IGNORECASE)
# `Prunus dom.`: the epithet abbreviated.
ABBREVIATIONS = {"Prunus dom.": "Prunus domestica"}

dropped: Counter[str] = Counter()


def parse_name(raw: str | None) -> tuple[str | None, str | None]:
    """`(species text, cultivar)` from one `Wetenschap` value.

    The species text still goes through `enforce_tree_schema`'s sanitiser,
    which reduces it to the accepted binomial.
    """
    if raw is None:
        return None, None
    text = " ".join(raw.split())
    if not text:
        return None, None
    text = NAME_FIXES.get(text, text)
    if text.lower() in UNIDENTIFIED:
        return UNKNOWN_SPECIES, None
    replaced = REPLACED_BY.match(text)
    if replaced:
        text = replaced.group(1)
    # A replacement character standing between genus and epithet is the
    # hybrid sign; anywhere else it is a mangled quote.
    text = re.sub(r"(?<=\s)�(?=\s)", "x", text)
    text = TRAILING_NOTE.sub("", text)
    for short, full in ABBREVIATIONS.items():
        if text.startswith(short + " "):
            text = full + text[len(short):]

    starts = [i for i, ch in enumerate(text) if ch in QUOTES]
    cultivar = None
    head = text
    if starts:
        first, last = starts[0], starts[-1]
        head = text[:first]
        inner = text[first + 1 : last] if last > first else text[first + 1 :]
        inner = " ".join(inner.split()).strip(" -")
        if inner and inner.lower() not in PLACEHOLDER_CULTIVARS and any(c.isalpha() for c in inner):
            cultivar = inner
    # Drop an all-caps trade name and an opening bracket before the quote:
    # `Zelkova serrata GREEN VASE ('Flekova')`, `Ulmus LUTECE ('Nanguen')`.
    words = [w for w in head.replace("(", " ").split() if not (len(w) > 2 and w.isupper())]
    head = CV_WORD.sub("", " ".join(words)).strip()
    return head or None, cultivar


def keep(feature: dict) -> bool:
    rec = feature.get("attributes") or {}
    if rec.get("Boomnummer") is None:
        dropped["no Boomnummer"] += 1
        return False
    name = " ".join((rec.get("Wetenschap") or "").split()).lower()
    if any(name.startswith(marker) for marker in NOT_A_TREE):
        dropped["species column says no tree"] += 1
        return False
    return True


def transform(features: list[dict]) -> pa.Table:
    tree_id, species, cultivar, plant_date, latitude, longitude = [], [], [], [], [], []
    for feature in features:
        rec = feature.get("attributes") or {}
        lat, lon = esri_point(feature.get("geometry"))
        name, selection = parse_name(rec.get("Wetenschap"))
        tree_id.append(f"{ID_PREFIX}{int(rec['Boomnummer'])}")
        species.append(name)
        cultivar.append(selection)
        plant_date.append(parse_plant_date_year(rec.get("plantjaar")))
        latitude.append(lat)
        longitude.append(lon)
    n = len(tree_id)
    return pa.table({
        "tree_id": pa.array(tree_id, type=pa.string()),
        "city": pa.array(["NLUTC"] * n, type=pa.string()),
        "species": pa.array(species, type=pa.string()),
        "cultivar": pa.array(cultivar, type=pa.string()),
        "plant_date": pa.array(plant_date, type=pa.date32()),
        "latitude": pa.array(latitude, type=pa.float64()),
        "longitude": pa.array(longitude, type=pa.float64()),
        "diameter_at_breast_height": pa.array([None] * n, type=pa.float64()),
    })


if __name__ == "__main__":
    tables = [
        stream_to_table(
            iter_features(layer, out_fields=FIELDS, return_geometry=True, out_sr=4326),
            transform, keep=keep, label=f"Utrecht {label}",
        )
        for label, layer in LAYERS.items()
    ]
    if dropped:
        print(
            "Utrecht: dropped " + ", ".join(f"{n} ({why})" for why, n in dropped.items()),
            file=sys.stderr,
        )
    table = pa.concat_tables(tables)
    table = validate_coordinates(table, city="Utrecht", city_code="NLUTC")
    table = enforce_tree_schema(table, city="Utrecht", data_source="UTRECHT_OPENDATA")
    emit(table)
