# The share of SDOT rows whose cultivar is dropped as unreadable above which the
# column has changed shape and the rules need a look.
MAX_DROPPED_CULTIVAR_SHARE = 0.05

QUOTES = "'\"‘’“”"
TRADEMARK = re.compile(r"\s*(?:\(R\)|®|™|\bTM\b)")
# `Genus epithet x ...`: a cross between two named species.
CROSS = re.compile(r"^([A-Z][a-z]+)\s+[a-z]+\.?\s+[xX×]\s+\S")
RANK = re.compile(r"(?:^|\s)(?:ssp|subsp|spp|sp|var|f|cv)(?:\.|\s|$)", re.IGNORECASE)
CV_NOTE = re.compile(r"\s+cv/hyb\b.*$", re.IGNORECASE)


def _is_possessive(s: str, i: int) -> bool:
    """`Krauter's`: an apostrophe between a letter and a closing `s`."""
    return (
        s[i] in "'’"
        and i > 0
        and s[i - 1].isalpha()
        and s[i + 1 : i + 2] == "s"
        and (i + 2 == len(s) or not s[i + 2].isalpha())
    )


def _quote_at(s: str, start: int) -> int:
    for i in range(start, len(s)):
        if s[i] in QUOTES and not _is_possessive(s, i):
            return i
    return -1


@cache
def parse_name(raw: str | None, width: int) -> tuple[str | None, str | None, bool]:
    """`(species text, cultivar, cultivar truncated)` from one raw name.

    The species text still goes through `enforce_tree_schema`'s sanitiser;
    this only separates what the sanitiser cannot see in SDOT's spellings.
    `width` is the column's length: a name that fills it and leaves its
    cultivar open was cut off.
    """
    if raw is None:
        return None, None, False
    s = " ".join(raw.replace("`", "'").split())
    if not s or s == SPR_LOOKUP_FAILURE:
        return None, None, False
    if s in NAME_FIXES:
        s = NAME_FIXES[s]
        if s is None:
            return None, None, False
    at_width = len(raw) >= width
    s = CV_NOTE.sub("", s)
    trademark = bool(TRADEMARK.search(s))
    s = " ".join(TRADEMARK.sub(" ", s).split())

    cultivar = None
    terminated = True
    open_at = _quote_at(s, 0)
    if open_at != -1:
        head = s[:open_at].strip()
        rest = s[open_at + 1 :]
        close_at = _quote_at(rest, 0)
        cultivar = rest[:close_at] if close_at != -1 else rest
        terminated = close_at != -1
    else:
        head = s
        tokens = head.split()
        if len(tokens) >= 2 and not RANK.search(head):
            at = 2 if tokens[1].lower() in ("x", "×") else 1
            start = at if trademark and tokens[at:at + 1] and tokens[at][:1].isupper() else at + 1
            trailing = tokens[start:]
            if trailing and all(t[:1].isupper() or t[:1].isdigit() for t in trailing):
                cultivar = " ".join(trailing)
                head = " ".join(tokens[:start])
                # A trademark marker closes the name; otherwise a run that
                # reaches the column's end may have been cut there.
                terminated = trademark or not at_width
    if cultivar is not None:
        cultivar = " ".join(cultivar.split()).strip(" -(") or None
    truncated = cultivar is not None and not terminated and at_width
    cross = CROSS.match(head)
    if cross:
        head = cross.group(1)
    return head or None, cultivar, truncated


def _genus(text: str | None) -> str | None:
    return text.split()[0] if text else None


def _taxon_key(text: str | None) -> str | None:
    """`Acer tataricum ssp.Ginnala` -> `Acer tataricum`; `Acer x Freemanii`
    -> `Acer x freemanii`: the name the completion table is keyed on."""
    if not text:
        return None
    tokens = text.split()
    n = 3 if len(tokens) > 2 and tokens[1].lower() in ("x", "×") else 2
    tokens = tokens[:n]
    return " ".join([tokens[0]] + [t.lower() for t in tokens[1:]])


class Seattle:
    def __init__(self) -> None:
        self.sdot_width = self._field_length(SDOT, "SCIENTIFIC_NAME")
        self.spr_width = 10_000  # Parks' names are not truncated
        self.vocabulary = self._vocabulary()
        self.dropped: Counter[str] = Counter()
        self.completed: Counter[str] = Counter()
        self.unreadable_cultivars: Counter[str] = Counter()
        self.sdot_rows = 0
        self.dropped_dates = 0

    @staticmethod
    def _field_length(layer: FeatureLayer, field: str) -> int:
        for spec in layer_metadata(layer).get("fields") or []:
            if spec.get("name") == field and spec.get("length"):
                return int(spec["length"])
        raise RuntimeError(f"Seattle: {layer.base} has no {field} length; schema changed")

    def _vocabulary(self) -> dict[str, set[tuple[str, str]]]:
        """Every full cultivar name the two layers spell out, by genus.

        SDOT's distinct names over all statuses (a removed tree still spells
        its cultivar) and the Parks species domain.
        """
        payload = get_json_with_retry(
            SDOT.query_url,
            params={
                "where": "SCIENTIFIC_NAME IS NOT NULL",
                "groupByFieldsForStatistics": "SCIENTIFIC_NAME",
                "outStatistics": json.dumps(
                    [{"statisticType": "count", "onStatisticField": "OBJECTID",
                      "outStatisticFieldName": "n"}]
                ),
                "f": "json",
            },
            timeout=SDOT.timeout,
        )
        if "features" not in payload or payload.get("exceededTransferLimit"):
            raise RuntimeError(f"Seattle SDOT species query was incomplete: {payload!r}"[:500])
        names = [(f["attributes"]["SCIENTIFIC_NAME"], self.sdot_width) for f in payload["features"]]
        names += [(name, self.spr_width) for name in coded_value_domain(SPR, "SPECIES").values()]
        vocab: dict[str, set[tuple[str, str]]] = defaultdict(set)
        for name, width in names:
            head, cultivar, truncated = parse_name(name, width)
            if cultivar and not truncated and head:
                vocab[_genus(head)].add((head, cultivar))
        return vocab

    def complete(self, head: str | None, prefix: str) -> str | None:
        genus = _genus(head)
        if genus is None:
            return None
        if (_taxon_key(head), prefix) in CULTIVAR_COMPLETIONS:
            return CULTIVAR_COMPLETIONS[(_taxon_key(head), prefix)]
        if len(prefix) < 3:
            return None
        found = {c for h, c in self.vocabulary.get(genus, ()) if c.lower().startswith(prefix.lower())}
        same = {c for h, c in self.vocabulary.get(genus, ())
                if h == head and c.lower().startswith(prefix.lower())}
        if len(same) == 1:
            return same.pop()
        if len(found) == 1:
            return found.pop()
        return None

    def name(self, raw: str | None, width: int) -> tuple[str | None, str | None]:
        head, cultivar, truncated = parse_name(raw, width)
        if truncated:
            full = self.complete(head, cultivar)
            if full is None:
                self.unreadable_cultivars[f"{raw}"] += 1
            else:
                self.completed[f"{cultivar} -> {full}"] += 1
            cultivar = full
        return head, cultivar

    # --- SDOT ---------------------------------------------------------------

    def keep_sdot(self, feature: dict) -> bool:
        rec = feature.get("attributes") or {}
        if not str(rec.get("UNITID") or "").strip():
            self.dropped["SDOT: no UNITID"] += 1
            return False
        if is_not_a_tree(rec.get("SCIENTIFIC_NAME")):
            self.dropped["SDOT: planting site"] += 1
            return False
        return True

    def sdot(self, features: list[dict]) -> pa.Table:
        cols = self._empty()
        for feature in features:
            rec = feature.get("attributes") or {}
            if rec.get("CURRENT_STATUS") != "INSVC":
                raise RuntimeError(f"Seattle SDOT row outside the in-service filter: {rec!r}")
            species, cultivar = self.name(rec.get("SCIENTIFIC_NAME"), self.sdot_width)
            lat, lon = esri_point(feature.get("geometry"))
            raw_dbh = rec.get("DIAM")
            planted_ms = rec.get("PLANTED_DATE")
            if planted_ms == PLACEHOLDER_PLANT_MS:
                self.dropped_dates += 1
                planted_ms = None
            self._append(
                cols,
                tree_id=f"sea-{str(rec['UNITID']).strip()}",
                species=species,
                cultivar=cultivar,
                plant_date=esri_ms_to_date(planted_ms),
                latitude=lat,
                longitude=lon,
                dbh=float(raw_dbh) if raw_dbh is not None else None,
            )
        self.sdot_rows += len(features)
        return self._table(cols)

    # --- Parks --------------------------------------------------------------

    def keep_spr(self, feature: dict) -> bool:
        rec = feature.get("attributes") or {}
        status = rec.get("STATUS")
        if status not in SPR_STANDING and status not in (SPR_SNAG, SPR_REMOVED):
            raise RuntimeError(f"Seattle Parks STATUS {status!r} is new; decide whether it is a tree")
        if status == SPR_REMOVED:
            self.dropped["Parks: removed"] += 1
            return False
        if rec.get("TREE_ID") is None:
            self.dropped["Parks: no TREE_ID"] += 1
            return False
        return True

    def spr(self, features: list[dict]) -> pa.Table:
        cols = self._empty()
        for feature in features:
            rec = feature.get("attributes") or {}
            if rec.get("STATUS") == SPR_SNAG:
                species, cultivar = DEAD_SPECIES, None
            else:
                species, cultivar = self.name(rec.get("SPECIES"), self.spr_width)
            lat, lon = esri_point(feature.get("geometry"))
            raw_dbh = rec.get("DBH_WL")
            self._append(
                cols,
                tree_id=f"sea-spr-{int(rec['TREE_ID'])}",
                species=species,
                cultivar=cultivar,
                plant_date=None,
                latitude=lat,
                longitude=lon,
                dbh=float(raw_dbh) if raw_dbh is not None else None,
            )
        return self._table(cols)

    # --- plumbing -----------------------------------------------------------

    @staticmethod
    def _empty() -> dict[str, list]:
        return {k: [] for k in ("tree_id", "species", "cultivar", "plant_date",
                                "latitude", "longitude", "dbh")}

    @staticmethod
    def _append(cols: dict[str, list], **values) -> None:
        for key, value in values.items():
            cols[key].append(value)

    @staticmethod
    def _table(cols: dict[str, list]) -> pa.Table:
        n = len(cols["tree_id"])
        return pa.table(
            {
                "tree_id": pa.array(cols["tree_id"], type=pa.string()),
                "city": pa.array(["USSEA"] * n, type=pa.string()),
                "species": pa.array(cols["species"], type=pa.string()),
                "cultivar": pa.array(cols["cultivar"], type=pa.string()),
                "plant_date": pa.array(cols["plant_date"], type=pa.date32()),
                "latitude": pa.array(cols["latitude"], type=pa.float64()),
                "longitude": pa.array(cols["longitude"], type=pa.float64()),
                "diameter_at_breast_height": pa.array(cols["dbh"], type=pa.float64()),
            }
        )

    def report(self) -> None:
        for reason, n in sorted(self.dropped.items()):
            print(f"Seattle: dropped {n:,} rows: {reason}", file=sys.stderr)
        print(
            f"Seattle: nulled {self.dropped_dates:,} SDOT planting dates stamped "
            "at the Esri epoch (1970-01-01)",
            file=sys.stderr,
        )
        completed = sum(self.completed.values())
        unreadable = sum(self.unreadable_cultivars.values())
        print(
            f"Seattle: completed {completed:,} truncated SDOT cultivars; dropped "
            f"{unreadable:,} it could not complete: "
            f"{dict(self.unreadable_cultivars.most_common(12))}",
            file=sys.stderr,
        )
        if self.sdot_rows and unreadable / self.sdot_rows > MAX_DROPPED_CULTIVAR_SHARE:
            raise RuntimeError(
                f"Seattle: {unreadable:,} of {self.sdot_rows:,} SDOT cultivars are "
                "truncated past reading; SCIENTIFIC_NAME has changed shape"
            )


