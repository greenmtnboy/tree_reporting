"""Seattle, WA's public trees: SDOT's street trees and Seattle Parks' trees.

Two layers on the City of Seattle's ArcGIS Online organisation, both listed
on data.seattle.gov (the city's Open Data Terms of Use: no licence is named;
"Unless otherwise indicated, data on this site does not require specific
attribution"):

* **SDOT Trees** (item db783659194f47ef8fbd8e010c102809, owner
  `Transportation_SeattleCityGIS`, `SDOT_Trees_CDL/FeatureServer/0`, feature
  class `SDOT.V_TREES`, refreshed daily): "both publicly and privately
  maintained trees in the public right of way".  276,760 rows on 2026-11-16,
  of which `CURRENT_STATUS` = `INSVC` 215,773; the rest are `REMOVED`
  (58,137), `PLANNED` (2,608) and a few hundred other work states
  (`OUTSVC`, `REMSCHD`, `UNDERCONS`, `PTNLINSTL`, ...).  The item description
  gives `CURRENT_STATUS = 'INSVC'` as "the recommended definition query for
  general use", and that is the filter here.  `OWNERSHIP` = `PRIV` (about
  170k in-service rows) is a street tree the abutting owner maintains: still
  a tree in the public right of way, on SDOT's inventory, and kept, as San
  Francisco keeps its privately maintained street trees.
* **SPR Tree View** (item 440724041fe54c92b78e5d935a11f668, owner
  `SeattleParks_SeattleCityGIS`, `SPR_Tree_View/FeatureServer/0`, refreshed
  weekly): "Seattle Parks and Recreation's Tree Inventory of individual trees
  on SPR property".  23,480 rows on 2026-11-16.  `STATUS` has the domain
  Existing / Removed / Snag; the view publishes no `Removed` rows today, and
  any that appear are dropped.  A `Snag` (879 rows) is a standing dead tree
  and publishes as the `Dead` sentinel.  A null `STATUS` (1,056 rows) is a
  tree whose status was never set and is kept.

**Why not "Combined Tree Point"** (item 15ca3b333b984fef8fda342ab0bba4d0): it
is a weekly presentation view of exactly these two inventories (its SDOT
rows are the 215,773 in-service trees, one for one; its Parks rows overlap
the SPR view on 22,408 ids) with every status, date and cultivar column
redacted, and its OBJECTIDs and GlobalIDs are regenerated by each reload
(OBJECTID ~75M on 240k rows).  The two source layers carry the status that
decides which rows are trees and SDOT's planting dates.

**Ids are the departments' own asset ids.**  Both layers are reloaded
(SDOT's OBJECTIDs run past 204M on 277k rows), so neither OBJECTID nor
GlobalID is stable.  SDOT's `UNITID` (`TRE-50439`, the Cityworks unit id) is
unique and non-null over the whole layer, all statuses; Parks' `TREE_ID`
(integer) is unique and non-null over its layer; both checked with a
`groupBy ... having COUNT > 1` statistics query (no rows).  Published as
`sea-TRE-50439` and `sea-spr-23759`, so the two id spaces cannot collide.

**Species is `SCIENTIFIC_NAME` (SDOT) and `SPECIES` (Parks).**  Both are
scientific names; neither layer's common-name column is read.  SDOT's column
is 30 characters wide and the long cultivar names are cut off
(`Prunus cerasifera `Thunderclou`), it writes cultivar quotes as backticks,
and some trade names carry no quotes at all (`Acer rubrum Red Sunset (R)`,
`Malus  Red Jewel TM`).  `parse_name` handles those:

* backticks are quotes, except as a possessive (`Krauter`s Vesuvius`);
* an unquoted run of capitalised words after the epithet is a cultivar, and a
  trademark marker (`TM`, `(R)`) also lets it follow the genus directly;
* an interspecific cross written `Genus a x b` (`Acer truncatum x A
  platanoides`, 3,905 Norwegian/Pacific Sunset maples; `Cornus kousa x nutt
  'Starlight'`) is a hybrid of no one species and publishes as the genus,
  Columbus's rule for its hybrid elms;
* a cultivar cut off at the column width is completed from the full names
  the two layers spell out elsewhere, or from `CULTIVAR_COMPLETIONS`, a
  short hand table of the well-known nursery names behind the commonest
  truncations; one neither can complete is dropped rather than published
  half-spelled;
* `cv/hyb` (`Prunus cerasifera cv/hyb`, 5,301 trees) is a note, not a name;
* the Parks layer writes `trigger_error` (538 rows) where its species lookup
  failed; that is an unknown species.

Thirteen SDOT rows are `Planting Site` and are dropped.

**DBH**: SDOT's `DIAM` is whole inches (mode 2, mean 9, a long tail; the
few over 200 are nulled by the schema).  Parks' `DBH_WL` is inches to a
decimal (mean 21, the park trees are older), from its tree work log.

**`PLANTED_DATE` (SDOT only) is `plant_date`**, filled on 214,989 in-service
rows.  Many are 1 January of a year (1977-01-01 is the commonest, 2,381
rows): a year-precision record, not a stamped default -- those trees' DBH
runs 11-23 in, about right for fifty-year-old street trees.  The one stamp
nulled here is the Esri epoch itself, 0 ms = 1970-01-01 (314 rows, a null
written as a number); the dates before it run back to 1950-01-01 (553 rows)
in year steps, the oldest street trees dated to the year, and are kept.  The
schema nulls the future dates.  The Parks layer has no planting
date.
"""

