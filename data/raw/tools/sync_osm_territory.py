"""Write each city's CITY_TERRITORY into its model's OSM datasource `where`.

Run after editing CITY_TERRITORY (from data/raw):

    uv run --no-project --with pyarrow --with "pytrilogy>=0.3.464" python tools/sync_osm_territory.py

A staged OSM extract keeps the territory it was cut with until its weekly
re-extract, so the city model filters it again on read (shared.ingest.
city_territory_where).  tests/test_city_territory.py fails while a model and
the table disagree.  Pass --check to only report the files that would change.

A town drawn by a polygon (boundaries/{code}.geojson) is filtered with
`geo_contains` against a constant in boundaries.preql, which this also
writes: one `const {code}_boundary` per file, so no model carries a thousand
corners inline.  A model that reads one gets `import ..boundaries;`.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

RAW = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(RAW))

from shared.boundary import boundary_codes, city_boundary  # noqa: E402
from shared.ingest import boundary_concept, city_territory_where  # noqa: E402

BOUNDARIES_MODEL = RAW / "boundaries.preql"
BOUNDARIES_IMPORT = "import ..boundaries;"
_IMPORTS = re.compile(r"(?:^import [^\n]*;\n)+", re.M)

# The staged parquet's file line, then an optional `where` already written.
_OSM_FILE = re.compile(
    r"(file `https://storage\.googleapis\.com/trilogy_public_models/duckdb/staging/"
    r"(?P<lc>[a-z]+)_osm_staging\.parquet`)(?:\nwhere [^;]*)?;"
)


def sync(text: str) -> str:
    def write(m: re.Match) -> str:
        code = m.group("lc").upper()
        return f"{m.group(1)}\nwhere {city_territory_where(code)};"

    synced = _OSM_FILE.sub(write, text)
    reads_boundary = "geo_contains(" in synced
    if reads_boundary and BOUNDARIES_IMPORT not in synced:
        synced = _IMPORTS.sub(lambda m: m.group(0) + BOUNDARIES_IMPORT + "\n", synced, count=1)
    elif not reads_boundary and BOUNDARIES_IMPORT in synced:
        synced = synced.replace(BOUNDARIES_IMPORT + "\n", "")
    return synced


def boundaries_model() -> str:
    """boundaries.preql: every polygon town's boundary as a geography constant."""
    lines = [
        "# Generated by tools/sync_osm_territory.py from boundaries/*.geojson; do not edit.",
        "#",
        "# One constant per town whose territory is a polygon (shared/boundary.py).  A",
        "# city model imports this to read its staged OSM extract through the town's",
        "# real line: `geo_contains({code}_boundary, geo_point(raw_longitude, raw_latitude))`.",
        "# Constants only, so importing it adds nothing to a job's bundle.",
        "",
    ]
    for code in boundary_codes():
        lines.append(f"const {boundary_concept(code)} <- geo_from_text('{city_boundary(code).wkt()}');")
    return "\n".join(lines) + "\n"


def city_models() -> list[Path]:
    return sorted(p for p in RAW.glob("*/*_tree_info.preql") if _OSM_FILE.search(p.read_text(encoding="utf-8")))


def main(argv: list[str]) -> int:
    check = "--check" in argv
    changed = []
    for path in city_models():
        text = path.read_text(encoding="utf-8")
        synced = sync(text)
        if synced != text:
            changed.append(path.relative_to(RAW).as_posix())
            if not check:
                path.write_text(synced, encoding="utf-8", newline="\n")
    wanted = boundaries_model()
    if not BOUNDARIES_MODEL.exists() or BOUNDARIES_MODEL.read_text(encoding="utf-8") != wanted:
        changed.append(BOUNDARIES_MODEL.name)
        if not check:
            BOUNDARIES_MODEL.write_text(wanted, encoding="utf-8", newline="\n")
    verb = "out of date" if check else "updated"
    print(f"{len(changed)} file(s) {verb}" + "".join(f"\n  {c}" for c in changed))
    return 1 if check and changed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
