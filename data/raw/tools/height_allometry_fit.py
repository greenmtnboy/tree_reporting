#!/usr/bin/env -S uv run
# /// script
# requires-python = ">=3.13"
# dependencies = ["duckdb<2"]
# ///
"""Fit the genus-level height model tree_predictions.preql applies.

    cd data/raw && uv run tools/height_allometry_fit.py --write     # refit from the published LIDAR heights
    cd data/raw && uv run tools/height_allometry_fit.py --check     # exit 1 if the model's block is stale

Why
---
The map draws a tree's sprite to scale, and a scale needs a height. Most
trees have none recorded: `height_m` comes from a LIDAR canopy survey and
only a city that imports `tree_height.preql` has one (docs/TREE_HEIGHT.md).
This model predicts a height from the stem diameter for every other tree,
the way `predicted_crown_width_m` predicts a crown. A measured height is
always used where there is one.

Source
------
The map's own published trees that carry both a measured diameter and a LIDAR
height: every row of each height city's parquet (`HEIGHT_CITIES`, which
`test_tree_height.py` keeps equal to the cities importing tree_height) except
the rows whose diameter is itself a model's -- the imagery predictions and
reviewed satellite detections. October 2026: 84,063 inventory trees in
Boston, Cambridge and the Arnold Arboretum. The genus comes from the
enrichment table, as `tree_predictions.preql` joins it.

Not Tallo, which `crown_allometry_fit.py` fits crowns on. Tallo's heights are
forest-grown, and on Cambridge's inventory (held out of a Boston-only fit) a
Tallo genus fit missed by a median 6.2 m and called a 24"+ street tree 29 m
against the survey's 19 m; a fit on Boston's LIDAR missed by 2.8 m with no
bias in any diameter band. Forest trees race for light; street trees are
pollarded, topped under wires and grown in the open.

Model
-----
    ln(height_m) = ln_a + b * ln(dbh_cm)

ordinary least squares in log-log space, per genus, back-transform bias
corrected (Baskerville 1972), so the prediction the model applies is

    height_m = scale * dbh_cm ** b        (dbh clamped to [1, dbh_max_cm])

the shape of the other two fits, for the same reason: pytrilogy has `**`
and no `exp` or `ln`. The exponent comes out at 0.1-0.5: height levels off
as the stem keeps thickening.

Fallback resolution happens at fit time, as in `dbh_age_fit.py`: a genus
whose own fit fails the gate carries its division's fit (angiosperm or
gymnosperm, from the enrichment table's `tree_form`), else the fit over every
usable tree. A genus with too few trees to attempt a fit has no row, and the
model falls through to the division constants `--write` renders into its
generated block. A palm gets no height, as it gets no crown.

The gate: n >= 100, 0.01 <= b <= 1.0, and a largest fitted stem of at
least 30 cm. There is no r2 floor, unlike the other two fits: a flat fit is
a true answer for a genus that stays small whatever its stem (Malus: r2
0.02, 9-11 m from 10 to 60 cm), and an r2 floor sent it to the angiosperm
fit, which calls a 30 cm crabapple 13 m.

What this model is not
----------------------
* Global. Every height today is from one metro, one climate and one
  vintage (2024). Applied to Melbourne or Tokyo it is a northeastern-US
  street tree of that diameter. The map labels every predicted height as an
  estimate, and the `cities` column says which cities stand behind each
  fit. Each new LIDAR city widens it: add it to `HEIGHT_CITIES` and refit.
* Free of the survey's own limits. A crown the segmentation merged lends its
  tallest point to every tree under it, which pushes small trees up a few
  metres; a tree planted since the survey is absent from the fit.
"""

from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

import duckdb

HERE = Path(__file__).resolve().parent
RAW = HERE.parent
COEFFICIENTS_CSV = RAW / "tree_height_coefficients.csv"
MODEL = RAW / "tree_predictions.preql"
BEGIN = "# BEGIN height_fallbacks -- generated by height_allometry_fit.py from tree_height_coefficients.csv; do not edit\n"
END = "# END height_fallbacks\n"

TREES_BASE_URL = "https://storage.googleapis.com/trilogy_public_models/duckdb/trees"
ENRICHMENT_URL = f"{TREES_BASE_URL}/tree_enrichment_v2.parquet"

# The cities whose published parquet carries a LIDAR `height_m`; the same set
# as the city models importing tree_height.preql (test_tree_height.py).
HEIGHT_CITIES: tuple[str, ...] = ("USBOS",)

# Rows whose diameter a model supplied: fitting on them would fit the model.
MODELLED_DIAMETER_SOURCES = ("PREDICTED_%", "SATELLITE_%")

MIN_N = 100
B_RANGE = (0.01, 1.0)
MIN_FITTED_DBH_MAX_CM = 30.0  # a fit made on saplings alone would clamp every mature tree to a sapling's height
DBH_MIN_CM = 2.5  # one inch: below it a "diameter" is a placeholder
DBH_MAX_INCHES = 200.0  # shared.ingest.DBH_MAX_INCHES

CSV_COLUMNS = [
    "level",           # genus | division | global
    "taxon",           # the genus / division name, or 'all'
    "fit_level",       # which fit a genus row carries: genus | division | global
    "fit_taxon",       # the taxon that fit came from
    "n",               # trees behind the fit
    "cities",          # the height cities they came from, ';'-separated
    "ln_a",
    "b",
    "sigma",
    "r2",
    "dbh_min_cm",
    "dbh_max_cm",
    "scale",           # exp(ln_a + sigma^2/2): height_m = scale * dbh_cm ** b
]

# `crown_fallback_class` in tree_predictions.preql, which decides which
# division constants a tree with no genus row gets.
CLASS_SQL = """
CASE
    WHEN t.species IN ('Unknown', 'Dead', 'Shrub') THEN 'all'
    WHEN e.tree_form = 'palm' OR t.species IN ('Palm', 'Cactus') THEN 'none'
    WHEN e.tree_form = 'conifer' THEN 'Gymnosperm'
    ELSE 'Angiosperm'
END
"""

FIT_SQL = """
SELECT
    {group} AS taxon,
    count(*) AS n,
    string_agg(DISTINCT city, ';' ORDER BY city) AS cities,
    regr_intercept(y, x) AS ln_a,
    regr_slope(y, x) AS b,
    sqrt(regr_syy(y, x) * (1 - regr_r2(y, x)) / (count(*) - 2)) AS sigma,
    regr_r2(y, x) AS r2,
    min(exp(x)) AS dbh_min_cm,
    max(exp(x)) AS dbh_max_cm
FROM usable
WHERE {group} IS NOT NULL {extra}
GROUP BY 1
HAVING count(*) >= {min_n}
"""


def city_parquet_url(code: str) -> str:
    return f"{TREES_BASE_URL}/{code.lower()}_tree_info_v2.parquet"


def load(conn: duckdb.DuckDBPyConnection, parquets: list[str], enrichment: str) -> None:
    conn.execute("INSTALL httpfs; LOAD httpfs")
    files = ", ".join(f"'{p}'" for p in parquets)
    modelled = " OR ".join(f"t.data_source LIKE '{pattern}'" for pattern in MODELLED_DIAMETER_SOURCES)
    conn.execute(
        f"""
        CREATE TABLE usable AS
        SELECT t.city, t.species, e.genus, {CLASS_SQL} AS division,
               ln(t.diameter_at_breast_height * 2.54) AS x, ln(t.height_m) AS y
        FROM read_parquet([{files}]) t
        LEFT JOIN read_parquet('{enrichment}') e ON e.species = t.species
        WHERE t.height_m > 0
          AND t.diameter_at_breast_height * 2.54 >= {DBH_MIN_CM}
          AND t.diameter_at_breast_height <= {DBH_MAX_INCHES}
          AND NOT ({modelled})
        """
    )
    conn.execute("DELETE FROM usable WHERE division = 'none'")


def passes_gate(row: dict) -> bool:
    return (
        row["n"] >= MIN_N
        and B_RANGE[0] <= row["b"] <= B_RANGE[1]
        and row["dbh_max_cm"] >= MIN_FITTED_DBH_MAX_CM
    )


def fits(conn: duckdb.DuckDBPyConnection, group: str, extra: str = "") -> dict[str, dict]:
    columns = ["taxon", "n", "cities", "ln_a", "b", "sigma", "r2", "dbh_min_cm", "dbh_max_cm"]
    rows = conn.execute(FIT_SQL.format(group=group, extra=extra, min_n=MIN_N)).fetchall()
    return {r[0]: dict(zip(columns, r)) for r in rows}


def with_scale(row: dict) -> dict:
    out = dict(row)
    out["scale"] = math.exp(row["ln_a"] + row["sigma"] ** 2 / 2)
    return out


def build_rows(conn: duckdb.DuckDBPyConnection) -> list[dict]:
    genus_fits = fits(conn, "genus")
    division_fits = fits(conn, "division", extra="AND division IN ('Angiosperm', 'Gymnosperm')")
    global_fit = fits(conn, "'all'")["all"]

    genus_division = dict(
        conn.execute(
            """
            SELECT genus, mode(division) FROM usable
            WHERE genus IS NOT NULL AND division IN ('Angiosperm', 'Gymnosperm')
            GROUP BY 1
            """
        ).fetchall()
    )

    rows: list[dict] = []
    for genus in sorted(genus_fits):
        division = genus_division.get(genus)
        candidates = [
            ("genus", genus, genus_fits[genus]),
            ("division", division, division_fits.get(division) if division else None),
            ("global", "all", global_fit),
        ]
        for fit_level, fit_taxon, fit in candidates:
            if fit is not None and passes_gate(fit):
                break
        else:  # pragma: no cover - the global fit always passes
            raise RuntimeError("no fit passed the gate, not even the global one")
        rows.append(
            {
                "level": "genus",
                "taxon": genus,
                "fit_level": fit_level,
                "fit_taxon": fit_taxon,
                **{k: v for k, v in with_scale(fit).items() if k != "taxon"},
            }
        )
    for division, fit in sorted(division_fits.items()):
        assert passes_gate(fit), f"the {division} fit failed the gate"
        rows.append(
            {"level": "division", "taxon": division, "fit_level": "division", "fit_taxon": division,
             **{k: v for k, v in with_scale(fit).items() if k != "taxon"}}
        )
    assert passes_gate(global_fit), "the global fit failed the gate"
    rows.append(
        {"level": "global", "taxon": "all", "fit_level": "global", "fit_taxon": "all",
         **{k: v for k, v in with_scale(global_fit).items() if k != "taxon"}}
    )
    return rows


def format_row(row: dict) -> dict[str, str]:
    out = {}
    for column in CSV_COLUMNS:
        value = row[column]
        out[column] = f"{value:.6g}" if isinstance(value, float) else str(value)
    return out


def write_csv(rows: list[dict]) -> None:
    with COEFFICIENTS_CSV.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow(format_row(row))


def read_csv_rows() -> list[dict[str, str]]:
    with COEFFICIENTS_CSV.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def render_block(rows: list[dict[str, str]]) -> str:
    """The division and global constants, as `const` declarations."""
    by_key = {(r["level"], r["taxon"]): r for r in rows}
    total = by_key[("global", "all")]
    lines = [
        BEGIN,
        f"# LIDAR heights of the map's own measured trees ({int(total['n']):,} in {total['cities'].replace(';', ', ')}): "
        "height_m = scale * dbh_cm ** b, dbh clamped to [1, dbh_max_cm]\n",
    ]
    for label, key in (
        ("angiosperm", ("division", "Angiosperm")),
        ("gymnosperm", ("division", "Gymnosperm")),
        ("global", ("global", "all")),
    ):
        row = by_key[key]
        lines.append(f"const {label}_height_scale <- {float(row['scale']):.6g};\n")
        lines.append(f"const {label}_height_b <- {float(row['b']):.6g};\n")
        lines.append(f"const {label}_height_n <- {int(row['n'])};\n")
        lines.append(f"const {label}_height_dbh_max_cm <- {float(row['dbh_max_cm']):.6g};\n")
    lines.append(END)
    return "".join(lines)


def splice_block(text: str, block: str) -> str:
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    return text[:start] + block + text[end:]


def current_block(text: str) -> str:
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    return text[start:end]


def report(conn: duckdb.DuckDBPyConnection, rows: list[dict]) -> None:
    genus_rows = [r for r in rows if r["level"] == "genus"]
    by_level: dict[str, int] = {}
    for r in genus_rows:
        by_level[r["fit_level"]] = by_level.get(r["fit_level"], 0) + 1
    print(f"{len(genus_rows)} genera: {by_level}", file=sys.stderr)
    print("height at 10 / 30 / 60 cm DBH, m:", file=sys.stderr)
    lookup = {r["taxon"]: r for r in genus_rows}
    for genus in ("Acer", "Quercus", "Gleditsia", "Tilia", "Ulmus", "Fraxinus", "Zelkova", "Pyrus",
                  "Prunus", "Platanus", "Malus", "Pinus", "Tsuga", "Ginkgo"):
        r = lookup.get(genus)
        if r is None:
            continue
        height = [r["scale"] * min(d, r["dbh_max_cm"]) ** r["b"] for d in (10, 30, 60)]
        print(f"  {genus:<12} {height[0]:5.1f} {height[1]:5.1f} {height[2]:5.1f}   "
              f"({r['fit_level']} fit, n={r['n']:,}, b={r['b']:.2f}, r2={r['r2']:.2f})", file=sys.stderr)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="refit from the published heights and rewrite the CSV and the model's fallback block")
    parser.add_argument("--check", action="store_true", help="exit 1 if the model's fallback block disagrees with the CSV")
    parser.add_argument("--parquet", action="append", help="a height city's parquet to fit on, instead of the published ones (repeatable; a local path works)")
    parser.add_argument("--enrichment", default=ENRICHMENT_URL, help="the enrichment parquet to take genus and form from")
    args = parser.parse_args()

    if args.check:
        text = MODEL.read_text(encoding="utf-8")
        if current_block(text) != render_block(read_csv_rows()):
            print(f"{MODEL.name}'s height_fallbacks block is stale; run height_allometry_fit.py --write", file=sys.stderr)
            return 1
        print("height_fallbacks block is current")
        return 0

    if not args.write:
        parser.error("one of --write or --check is required")

    conn = duckdb.connect()
    load(conn, args.parquet or [city_parquet_url(code) for code in HEIGHT_CITIES], args.enrichment)
    rows = build_rows(conn)
    write_csv(rows)
    text = MODEL.read_text(encoding="utf-8")
    MODEL.write_text(splice_block(text, render_block(read_csv_rows())), encoding="utf-8")
    print(f"wrote {len(rows)} rows to {COEFFICIENTS_CSV.name} and the fallback block in {MODEL.name}", file=sys.stderr)
    report(conn, rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
