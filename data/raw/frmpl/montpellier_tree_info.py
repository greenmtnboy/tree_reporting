"""Montpellier's municipal tree inventory ("Arbres de Montpellier").

Source: the GeoJSON resource of the package `arbres-de-montpellier` (alias
`arbres-dalignement-de-montpellier`) on Montpellier Méditerranée Métropole's
open-data portal (https://data.montpellier3m.fr/dataset/arbres-de-montpellier),
published by Montpellier Méditerranée Métropole under the Open Data Commons
Open Database License (ODbL) -- the package's `license_id` is `odc-odbl`.
**60,882 features** when this was written, all in WGS84.  The file is
regenerated by the portal every morning (its HTTP `Last-Modified` moved to
06:01 UTC on the day this was written while the CKAN resource record still
says 2022); see `montpellier_update_time.py`.

The portal's CKAN is an emulation: `resource_show` nests its result one level
deeper than CKAN does and carries `last_modified` as "Date changed\\t...", so
`shared.platforms.ckan` cannot read it.  The file URL is read directly; the
CSV and KML forms carry the same seven columns (the CSV has no coordinates),
and the shapefile is the same layer in Lambert 93.

**Coverage.**  The description speaks of a 2025-2026 mobile-mapping inventory
of the Métropole's roadside trees (2025) and the Ville's parks, schools and
other municipal grounds (2026), but the published layer is the Ville de
Montpellier's: every feature lies inside the commune (lon 3.809-3.938, lat
43.572-43.652), `quartier` is one of Centre / Nord-Ouest / Sud-Est, and
`commune`, `secteur` and `adresse` are null on every row.

**Keyed on `id_arbre`**, verified non-null, all-digit and unique over all
60,882 features.  Published as `montpellier-12345`.  A row without one is
dropped with a count; a repeat raises in `enforce_tree_schema`.

**Species is `nom_latin`**, a botanical name with the hybrid sign written as
`×` (`Platanus × hispanica`, `× Hesperotropsis leylandii`) and `Genus sp.`
for a tree named to the genus; no cultivars are recorded.  A blank (a single
space, 3.8k rows, with a blank `nom_commun` too) is an unidentified tree and
is published as unknown.  A leading mark names a nothogenus
(`× Chitalpa tashkentensis`, `× Hesperotropsis leylandii`, 59 rows) and is
dropped, as Toulouse and Rennes do: the shared hygiene would otherwise publish
`X chitalpa tashkentensis`, a key of its own.  `nom_commun` is the French
common name and is not used.

**Not published by the portal**: no trunk measure, no height, no crown, no
planting date, no status column -- the description's "dimensions, structure
du houppier, état général" are not in the open export.  There is no stump or
planting-site flag to drop on.
"""

import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path

import pyarrow as pa

sys.path.insert(0, str(Path(__file__).parent.parent))
from shared.ingest import (
    emit,
    enforce_tree_schema,
    get_with_retry,
    validate_coordinates,
)

# Kept in step with montpellier_update_time.py.
SOURCE_URL = (
    "https://data.montpellier3m.fr/sites/default/files/ressources/MMM_MTP_Arbres.json"
)
FIELDS = ("id_arbre", "nom_latin")


def clean(value) -> str | None:
    if value is None:
        return None
    text = " ".join(str(value).split())
    return text or None


def parse_species(value) -> str | None:
    """The botanical name, with a nothogenus's leading hybrid mark dropped."""
    text = clean(value)
    if text is None:
        return None
    if text[:2].lower() in ("× ", "x "):
        text = text[2:].strip()
    return text or None


def read_features() -> list[dict]:
    response = get_with_retry(SOURCE_URL, timeout=300)
    try:
        payload = json.loads(response.content.decode("utf-8-sig"))
    except ValueError as exc:
        raise RuntimeError(
            f"Montpellier ingest: {SOURCE_URL} did not parse as JSON ({exc}); got "
            f"{response.headers.get('content-type')}, {len(response.content)} bytes"
        ) from exc
    features = payload.get("features")
    if not features:
        raise RuntimeError(
            f"Montpellier ingest: {SOURCE_URL} has no features "
            f"(keys {sorted(payload)[:8]})"
        )
    missing = [f for f in FIELDS if f not in (features[0].get("properties") or {})]
    if missing:
        raise RuntimeError(
            f"Montpellier ingest: the layer is missing field(s) {missing}; "
            "the portal changed its schema"
        )
    return features


def transform(features: list[dict]) -> pa.Table:
    tree_id: list[str] = []
    species: list[str | None] = []
    latitude: list[float | None] = []
    longitude: list[float | None] = []
    dropped: Counter[str] = Counter()

    for feature in features:
        props = feature.get("properties") or {}
        key = clean(props.get("id_arbre"))
        if key is None:
            dropped["no id_arbre"] += 1
            continue
        geometry = feature.get("geometry") or {}
        coords = geometry.get("coordinates") if geometry.get("type") == "Point" else None
        if not coords or len(coords) < 2:
            dropped["no point geometry"] += 1
            continue
        tree_id.append(f"montpellier-{key}")
        species.append(parse_species(props.get("nom_latin")))
        longitude.append(float(coords[0]))
        latitude.append(float(coords[1]))

    print(
        f"Montpellier OpenData: {len(features)} features, {len(tree_id)} kept; "
        f"dropped {dict(dropped) or 0}",
        file=sys.stderr,
    )
    n = len(tree_id)
    return pa.table(
        {
            "tree_id": pa.array(tree_id, type=pa.string()),
            "city": pa.array(["FRMPL"] * n, type=pa.string()),
            "species": pa.array(species, type=pa.string()),
            "plant_date": pa.array([None] * n, type=pa.date32()),
            "latitude": pa.array(latitude, type=pa.float64()),
            "longitude": pa.array(longitude, type=pa.float64()),
            "diameter_at_breast_height": pa.array([None] * n, type=pa.float64()),
        }
    )


def main() -> None:
    table = transform(read_features())
    table = validate_coordinates(table, city="Montpellier", city_code="FRMPL")
    table = enforce_tree_schema(
        table, city="Montpellier", data_source="MONTPELLIER_OPENDATA"
    )
    emit(table)


if __name__ == "__main__":
    main()
