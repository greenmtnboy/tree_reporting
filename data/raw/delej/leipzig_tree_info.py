#!/usr/bin/env -S uv run
# /// script
# requires-python = ">=3.13"
# dependencies = ["pyarrow", "requests", "pytrilogy"]
# ///
"""Leipzig's tree register (Baumkataster), from the city's WFS.

Source: `OpenData:Baeume` on `geodienste.leipzig.de/l3/OpenData/wfs`, Stadt
Leipzig's GeoServer, catalogued on opendata.leipzig.de as "Baumkataster,
Stadt Leipzig" (`baumkataster-stadt-leipzig1`, published by the Amt für
Stadtgrün und Gewässer).  The dataset-level licence field is empty, but every
distribution of the record states `dl-by-de/2.0` -- Datenlizenz Deutschland
-- Namensnennung -- 2.0, attribution "Stadt Leipzig".  The register holds the
street trees and the trees on city property -- parks, cemeteries, allotments,
the city forest, waterside, sports grounds, schools and nurseries -- and the
catalogue says it is still being completed: **187,531 points** when this was
written.  The layer is regenerated by an FME load every day (`fme_tstamp` is
that load's date on every row).

**Keyed on `objektkuerzel` + `baumnummer`**, the site code and the tree's
number within it (`02334` / `12666`, `F.1` / `130738/1`): checked over the
whole layer, 187,531 distinct pairs in 187,531 rows, `baumnummer` never
null.  `baumnummer` alone repeats (186,181 distinct).  172 trees (woodland,
nurseries, parks; `G805`) have no site code; their numbers are each unique
over the whole layer, so they are keyed `leipzig-nosite-{baumnummer}` rather
than dropped (the id moves if the city later gives them a site).
`objectid` is unique but is not an id: it ran 38,586,049 to 38,773,579 --
exactly one value per row, a sequence the daily FME load hands out afresh --
so it would rename every tree every day.  A row with no tree number or no
point, or a repeated id, is dropped with a count (none were).

**Species is `ga_lang_wiss`**, the Latin name with the cultivar quoted
(`Tilia cordata 'Greenspire'`).  The cultivar is cut out here, first quote to
last, and passed as `cultivar`: the register writes an apostrophe inside a
cultivar (`'Westhof´s Glorie'`, `'Paul's Scarlet'`), which the shared
splitter would read as the closing quote.
`Tilia species` / `Tilia spec.` is a tree identified to genus, which the
shared hygiene folds to the genus.  `Bestandsfläche` (a stand of trees
recorded as one point, 154 rows), `unbekannt` and `Unklar` are not a taxon
and publish as `Unknown`, as do the 492 rows with no name.
`ga_lang_deutsch` is the German common name and is not mapped.

**`st_umfang` is the trunk circumference in whole centimetres** (median 79)
and `st_durchm` the diameter (median 25); the two agree (circumference /
diameter has median 3.14).  The circumference is read because it is the
measured and finer-grained of the two (diameters under 1 cm read 0); the
diameter is the fallback.  `kr_durchm` is the crown diameter in metres
(median 6), published as `crown_width_m`.  `baumhoehe` is the height in
metres, which the canonical schema has no column for.  `pflanzjahr` is a
planting year (decades dominate -- estimates, not a stamped default), published
as January 1 of that year; a few impossible years (12, 140, 1005) are nulled
by the shared schema.  `standzeitraum` is the age implied by that year.

The layer has a felling date (`gefaellt_am`, null on every row) and a
replanting note (`nachpflanzung_geplant`, on 270 trees that are still
standing and measured), so no removed tree, stump or empty site is flagged.
"""

import sys
from datetime import date
from pathlib import Path

import pyarrow as pa

sys.path.insert(0, str(Path(__file__).parent.parent))
from shared.ingest import (  # noqa: E402
    circumference_cm_to_dbh_inches,
    emit,
    enforce_tree_schema,
    get_json_with_retry,
    parse_plant_date_year,
    stream_to_table,
    validate_coordinates,
)
from shared.platforms.wfs import WfsLayer, iter_wfs_features  # noqa: E402

LAYER = WfsLayer("https://geodienste.leipzig.de/l3/OpenData/wfs", "OpenData:Baeume", timeout=300)
PROPERTIES = [
    "objectid",
    "objektkuerzel",
    "baumnummer",
    "ga_lang_wiss",
    "pflanzjahr",
    "kr_durchm",
    "st_durchm",
    "st_umfang",
    "geom",
]
PAGE_SIZE = 25000

NOT_A_TAXON = frozenset({"bestandsfläche", "unbekannt", "unklar"})


def clean(value) -> str | None:
    if value is None:
        return None
    text = " ".join(str(value).split())
    return text or None


def parse_name(name) -> tuple[str | None, str | None]:
    """(species, cultivar) from the register's Latin name; species None for a non-taxon."""
    text = clean(name)
    if text is None or text.lower() in NOT_A_TAXON:
        return None, None
    first, last = text.find("'"), text.rfind("'")
    if first == -1:
        return text, None
    species = clean(text[:first])
    cultivar = clean(text[first + 1 : last] if last > first else text[first + 1 :])
    # The acute accent is the register's apostrophe (`Westhof´s Glorie`).
    return species, cultivar.replace("´", "'") if cultivar else None


def parse_number(value, counts: dict[str, int]) -> float | None:
    if value in (None, ""):
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        counts["bad_number"] += 1
        return None


def feature_count() -> int:
    """`numberMatched` from a one-feature GeoJSON page.

    This GeoServer answers `resultType=hits` in XML whatever `outputFormat`
    asks for, so `shared.platforms.wfs.wfs_feature_count` cannot read it.
    """
    payload = get_json_with_retry(
        LAYER.base_url,
        params=LAYER.params(count=1, propertyName="objectid"),
        timeout=LAYER.timeout,
    )
    total = payload.get("numberMatched")
    if not isinstance(total, int):
        raise RuntimeError(f"{LAYER.type_name}: GetFeature returned no numberMatched")
    return total


def make_transform(counts: dict[str, int], seen: set[str]):
    def transform(features: list[dict]) -> pa.Table:
        tree_id: list[str] = []
        species: list[str | None] = []
        cultivar: list[str | None] = []
        plant_date: list[date | None] = []
        latitude: list[float] = []
        longitude: list[float] = []
        dbh: list[float | None] = []
        crown: list[float | None] = []

        for feature in features:
            counts["read"] += 1
            props = feature.get("properties") or {}
            site = clean(props.get("objektkuerzel"))
            number = clean(props.get("baumnummer"))
            geometry = feature.get("geometry") or {}
            coords = geometry.get("coordinates") if geometry.get("type") == "Point" else None
            if number is None or not coords or len(coords) < 2:
                counts["unusable"] += 1
                continue
            if site is None:
                counts["no_site"] += 1
                key = f"leipzig-nosite-{number}"
            else:
                key = f"leipzig-{site}-{number}"
            if key in seen:
                counts["duplicate"] += 1
                continue
            seen.add(key)

            year = props.get("pflanzjahr")
            if year not in (None, ""):
                try:
                    int(year)
                except (TypeError, ValueError):
                    counts["bad_number"] += 1
            circ = parse_number(props.get("st_umfang"), counts)
            diameter = parse_number(props.get("st_durchm"), counts)
            if circ:
                size = circumference_cm_to_dbh_inches(circ)
            elif diameter:
                size = diameter / 2.54
            else:
                size = None

            name, selection = parse_name(props.get("ga_lang_wiss"))
            tree_id.append(key)
            species.append(name)
            cultivar.append(selection)
            plant_date.append(parse_plant_date_year(year))
            longitude.append(float(coords[0]))
            latitude.append(float(coords[1]))
            dbh.append(size)
            crown.append(parse_number(props.get("kr_durchm"), counts))

        return pa.table(
            {
                "tree_id": pa.array(tree_id, type=pa.string()),
                "city": pa.array(["DELEJ"] * len(tree_id), type=pa.string()),
                "species": pa.array(species, type=pa.string()),
                "cultivar": pa.array(cultivar, type=pa.string()),
                "plant_date": pa.array(plant_date, type=pa.date32()),
                "latitude": pa.array(latitude, type=pa.float64()),
                "longitude": pa.array(longitude, type=pa.float64()),
                "diameter_at_breast_height": pa.array(dbh, type=pa.float64()),
                "crown_width_m": pa.array(crown, type=pa.float64()),
            }
        )

    return transform


def main() -> None:
    expected = feature_count()
    counts = {"read": 0, "unusable": 0, "no_site": 0, "duplicate": 0, "bad_number": 0}
    seen: set[str] = set()
    pages = iter_wfs_features(
        LAYER, sort_by="objectid", properties=PROPERTIES, page_size=PAGE_SIZE
    )
    table = stream_to_table(pages, make_transform(counts, seen), label="Leipzig OpenData")
    if counts["read"] != expected:
        raise RuntimeError(
            f"Leipzig OpenData: read {counts['read']} feature(s) but the layer reports "
            f"{expected}; refusing to publish a partial register (a daily reload mid-read?)"
        )
    if counts["bad_number"] > 0.01 * max(counts["read"], 1):
        raise RuntimeError(
            f"Leipzig OpenData: {counts['bad_number']} unreadable year/girth/crown value(s) "
            f"(>1% of {counts['read']}); the fields changed shape"
        )
    print(
        f"Leipzig OpenData: read {counts['read']} of {expected}; dropped "
        f"{counts['unusable']} row(s) with no tree number or point and "
        f"{counts['duplicate']} repeated id(s); {counts['no_site']} keyed without a site "
        f"code; {counts['bad_number']} unreadable numeric "
        f"value(s) nulled; leaving {table.num_rows}",
        file=sys.stderr,
    )
    table = validate_coordinates(table, city="Leipzig", city_code="DELEJ")
    table = enforce_tree_schema(table, city="Leipzig", data_source="LEIPZIG_OPENDATA")
    emit(table)


if __name__ == "__main__":
    main()
