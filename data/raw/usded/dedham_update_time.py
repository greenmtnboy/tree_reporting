"""Freshness probe for Dedham's tree inventory: the layer's own last data
edit (`editingInfo`); the row edit-date columns are empty."""

import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
from shared.platforms.arcgis import FeatureLayer, layer_last_edit  # noqa: E402
from shared.ingest import emit_freshness  # noqa: E402

LAYER = FeatureLayer(
    "https://services1.arcgis.com/me41C4ZTLmDO2rPK/arcgis/rest/services/"
    "production_DBO_Trees/FeatureServer/0"
)


def fetch_modified_at() -> datetime:
    return layer_last_edit(LAYER)


if __name__ == "__main__":
    emit_freshness("USDED", fetch_modified_at)
