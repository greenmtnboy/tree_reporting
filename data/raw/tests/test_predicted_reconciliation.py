"""What the shared cluster merge does with a bulk prediction (`PREDICTED_`).

Planned and run the way test_satellite_reconciliation.py runs SF: Boston's own
build SQL, generated by pytrilogy, with every python source and the staged OSM
parquet repointed at fixture parquets.  A prediction nobody reviewed has to be
the weakest row in the merge:

* beside an inventory tree, a reviewed detection or an OSM node, it is
  absorbed and lends the survivor nothing -- not a species to fill a gap, not
  a crown, not a position;
* alone, it publishes as its own tree with its own values;
* beside another prediction, both publish: nothing ever joins a prediction;
* and two OSM nodes in a cell still stay two trees, so the OSM tier that
  absorbs predictions is not open to OSM rows themselves.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

RAW_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(RAW_DIR))

MODEL = RAW_DIR / "usbos" / "boston_tree_info.preql"

# Well-separated points in Boston; partners sit ~1.3 m away, inside the 5 m
# Boston's 10 m cell guarantees.
P1 = (42.3000, -71.0800)
P2 = (42.3050, -71.0850)
P3 = (42.3100, -71.0900)
P4 = (42.3150, -71.0950)
P5 = (42.3200, -71.1000)
P6 = (42.3250, -71.1050)
P7 = (42.3300, -71.1100)
NUDGE = 0.000012  # ~1.3 m of latitude


def near(point, times: int = 1):
    return (point[0] + NUDGE * times, point[1])


COLUMNS = (
    "tree_id", "city", "data_source", "species", "tree_name", "plant_date",
    "diameter_at_breast_height", "latitude", "longitude", "submission_photo_url",
    "cultivar", "crown_width_m",
)
# Boston's own script emits the portal's spelling for four columns.
BOSTON_RENAME = {
    "tree_id": "id", "species": "spp_bot", "plant_date": "date_plant",
    "diameter_at_breast_height": "dbh",
}

# (tree_id, data_source, species, dbh, crown, point)
MUNICIPAL = [
    # An inventory row with no species (the ingest's Unknown sentinel) and no
    # crown.  A genus outranks Unknown in the species contest, so before the
    # predicted class this is exactly the gap a prediction would have filled.
    ("bos-1", "CITY_OF_BOSTON", "Unknown", 12.0, None, P1),
    ("bos-2", "CITY_OF_BOSTON", "Quercus rubra", 20.0, None, P6),
]
SATELLITE = [("sat-x", "SATELLITE_USBOS", "Tilia cordata", None, 7.0, P5)]
OSM = [
    ("osm-1", "OSM_USBOS", "Unknown", None, None, P3),
    ("osm-2", "OSM_USBOS", "Unknown", None, None, near(P6)),
    # Two OSM nodes a metre apart: they stay two trees.
    ("osm-3", "OSM_USBOS", "Unknown", None, None, P7),
    ("osm-4", "OSM_USBOS", "Unknown", None, None, near(P7)),
]
PREDICTED = [
    ("pred-a", "PREDICTED_USBOS", "Acer", None, 5.0, near(P1)),
    ("pred-b", "PREDICTED_USBOS", "Platanus", None, 6.0, P2),
    ("pred-c", "PREDICTED_USBOS", "Gleditsia", None, 4.0, near(P3)),
    ("pred-d", "PREDICTED_USBOS", "Acer", None, 3.0, P4),
    ("pred-e", "PREDICTED_USBOS", "Acer", None, 3.5, near(P4)),
    ("pred-f", "PREDICTED_USBOS", "Malus", None, 2.0, near(P5)),
    ("pred-g", "PREDICTED_USBOS", "Ulmus", None, 9.0, near(P6, 2)),
]


def write_rows(conn, path: Path, rows, *, rename: dict[str, str] | None = None) -> None:
    conn.execute("DROP TABLE IF EXISTS src")
    conn.execute(
        """
        CREATE TABLE src (
            tree_id VARCHAR, city VARCHAR, data_source VARCHAR, species VARCHAR,
            tree_name VARCHAR, plant_date DATE, diameter_at_breast_height DOUBLE,
            latitude DOUBLE, longitude DOUBLE, submission_photo_url VARCHAR, cultivar VARCHAR,
            crown_width_m DOUBLE
        )
        """
    )
    if rows:
        conn.executemany(
            "INSERT INTO src VALUES (?, 'USBOS', ?, ?, NULL, NULL, ?, ?, ?, NULL, NULL, ?)",
            [(tid, source, species, dbh, *point, crown) for tid, source, species, dbh, crown, point in rows],
        )
    select = ", ".join(f"{col} AS {(rename or {}).get(col, col)}" for col in COLUMNS)
    conn.execute(f"COPY (SELECT {select} FROM src) TO '{path.as_posix()}' (FORMAT PARQUET)")


@pytest.fixture(scope="module")
def published(tmp_path_factory) -> dict[str, dict]:
    import duckdb
    from trilogy import Dialects, Environment
    from trilogy.dialect.config import DuckDBConfig

    from test_satellite_reconciliation import write_modifications

    tmp = tmp_path_factory.mktemp("predicted_reconciliation")
    conn = duckdb.connect()
    by_script = {
        "boston_tree_info.py": (MUNICIPAL, BOSTON_RENAME),
        "arboretum_tree_info.py": ([], None),
        "cambridge_tree_info.py": ([], None),
        "brookline_tree_info.py": ([], None),
        "somerville_tree_info.py": ([], None),
        "belmont_tree_info.py": ([], None),
        "watertown_tree_info.py": ([], None),
        "community_tree_info.py": ([], None),
        "satellite_tree_info.py": (SATELLITE, None),
        "predicted_tree_info.py": (PREDICTED, None),
        "usbos_osm_staging.parquet": (OSM, None),
    }
    fixtures = {}
    for script, (rows, rename) in by_script.items():
        fixtures[script] = tmp / f"{script}.parquet"
        write_rows(conn, fixtures[script], rows, rename=rename)
    fixtures["tree_modification_info.py"] = tmp / "modifications.parquet"
    write_modifications(conn, fixtures["tree_modification_info.py"], [])

    env = Environment(working_path=MODEL.parent)
    env.parse(MODEL.read_text(encoding="utf-8"))
    executor = Dialects.DUCK_DB.default_executor(
        environment=env, conf=DuckDBConfig(enable_python_datasources=True)
    )
    sql = executor.update_datasource(env.datasources["boston_tree_info"], dry_run=True)
    assert sql is not None
    sql = re.sub(r'^.*?INSERT INTO "[^"]*"\s*', "", sql, count=1, flags=re.S)
    assert sql.lstrip().upper().startswith("WITH"), sql[:200]

    stamp = "TIMESTAMPTZ '2026-01-01 00:00:00+00'"
    probe = "(SELECT " + ", ".join(
        f"{stamp} AS {col}"
        for col in (
            "data_updated_through",
            "usbos_community_data_updated_through",
            "usbos_satellite_data_updated_through",
            "usbos_predicted_data_updated_through",
        )
    ) + ")"

    def repoint(match: re.Match) -> str:
        script = Path(match.group(1)).name
        if script in fixtures:
            return f"read_parquet('{fixtures[script].as_posix()}')"
        assert script.endswith(("_update_time.py", "_probe.py")), script
        return probe

    sql = re.sub(r"uv_run\('([^']+)'(?:,\s*args := '(?:[^']|'')*')?\)", repoint, sql)
    sql = re.sub(
        r"read_parquet\('[^']*usbos_osm_staging\.parquet[^']*'\)",
        f"read_parquet('{fixtures['usbos_osm_staging.parquet'].as_posix()}')",
        sql,
    )
    # The LIDAR height lookup (../tree_height.preql): empty here, so no tree
    # matches a crown; test_tree_height.py covers the matching.
    sql = re.sub(
        r"read_parquet\('[^']*usbos_canopy_height\.parquet[^']*'\)",
        "(SELECT CAST(NULL AS BIGINT) AS canopy_cell, CAST(NULL AS VARCHAR) AS canopy_crown_id, "
        "CAST(NULL AS DOUBLE) AS canopy_height_m, CAST(NULL AS DOUBLE) AS canopy_crown_radius_m, "
        "CAST(NULL AS VARCHAR) AS canopy_source WHERE false)",
        sql,
    )
    # ../tree_height.preql's grid `const`s render as bound parameters.
    height_model = (RAW_DIR / "tree_height.preql").read_text(encoding="utf-8")
    for name, value in re.findall(r"^const (\w+) <- ([-\d.]+);", height_model, re.M):
        sql = re.sub(rf":{name}\b", value, sql)
    assert "uv_run" not in sql and "storage.googleapis.com" not in sql, sql
    cursor = conn.execute(sql)
    columns = [d[0] for d in cursor.description]
    return {row["tree_id"]: row for row in (dict(zip(columns, r)) for r in cursor.fetchall())}


def absorbed(row) -> list[str]:
    return row["merged_tree_ids"].split(",") if row["merged_tree_ids"] else []


def test_one_survivor_per_cluster(published):
    assert set(published) == {
        "bos-1", "bos-2", "sat-x", "osm-1", "osm-3", "osm-4", "pred-b", "pred-d", "pred-e",
    }


def test_an_inventory_tree_absorbs_a_prediction_and_takes_none_of_it(published):
    row = published["bos-1"]
    assert absorbed(row) == ["pred-a"]
    assert row["merged_sources"] == "CITY_OF_BOSTON,PREDICTED_USBOS"
    # The inventory left species and crown empty; the model's guesses stay out.
    assert row["species"] == "Unknown"
    assert row["crown_width_m"] is None
    assert (row["latitude"], row["longitude"]) == P1


def test_a_lone_prediction_publishes_its_own_values(published):
    row = published["pred-b"]
    assert row["merged_sources"] == "PREDICTED_USBOS"
    assert row["species"] == "Platanus"
    assert row["crown_width_m"] == 6.0
    assert (row["latitude"], row["longitude"]) == P2
    assert absorbed(row) == []


def test_an_osm_node_absorbs_a_prediction(published):
    row = published["osm-1"]
    assert absorbed(row) == ["pred-c"]
    assert row["species"] == "Unknown"
    assert row["crown_width_m"] is None


def test_two_predictions_side_by_side_stay_two_trees(published):
    assert published["pred-d"]["cluster_id"] == "pred-d"
    assert published["pred-e"]["cluster_id"] == "pred-e"


def test_a_reviewed_detection_owns_a_prediction_beside_it(published):
    """The promotion path: a person confirms the tree in the reviewer, its
    `sat-` row publishes, and the prediction folds into it."""
    row = published["sat-x"]
    assert absorbed(row) == ["pred-f"]
    assert row["species"] == "Tilia cordata"
    assert row["crown_width_m"] == 7.0


def test_the_inventory_wins_over_osm_and_a_prediction_together(published):
    row = published["bos-2"]
    assert absorbed(row) == ["osm-2", "pred-g"]
    assert row["species"] == "Quercus rubra"
    assert row["crown_width_m"] is None


def test_two_osm_nodes_still_stay_two_trees(published):
    assert published["osm-3"]["cluster_id"] == "osm-3"
    assert published["osm-4"]["cluster_id"] == "osm-4"
